import { existsSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const functionsRoot = resolve(import.meta.dir, "../src/functions");
const generatedHeader = "// Generated by scripts/fnLoader.ts.";
const generatedFiles = new Map<string, string | null>();

function renderArray(items: string[]): string[] {
  const line = `export default [${items.join(", ")}];`;
  if (line.length <= 100) return [line];
  return ["export default [", ...items.map((item) => `  ${item},`), "];"];
}

function generateDirectory(directory: string): boolean {
  const entries = readdirSync(directory, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  );
  const sourceFiles = entries.filter(
    (entry) => entry.isFile() && entry.name.endsWith(".ts") && entry.name !== "index.ts",
  );
  const childDirectories = entries.filter((entry) => entry.isDirectory());
  const childCategories = childDirectories
    .filter((entry) => generateDirectory(join(directory, entry.name)))
    .map((entry) => entry.name);

  for (const file of sourceFiles) {
    const source = readFileSync(join(directory, file.name), "utf8");
    const definitions = source.match(/\bnew\s+AntamFunction\s*\(/g)?.length ?? 0;
    if (definitions !== 1) {
      throw new Error(
        `${join(directory, file.name)} must contain exactly one AntamFunction (found ${definitions})`,
      );
    }
  }

  if (sourceFiles.length === 0 && childCategories.length === 0) {
    const indexPath = join(directory, "index.ts");
    if (
      existsSync(indexPath) &&
      readFileSync(indexPath, "utf8").startsWith(`${generatedHeader}\n`)
    ) {
      generatedFiles.set(indexPath, null);
    }
    return false;
  }

  const imports = [
    ...sourceFiles.map((file, index) => `import fn${index} from "./${file.name.slice(0, -3)}";`),
    ...childCategories.map((category, index) => `import category${index} from "./${category}";`),
  ];
  const exports = [
    ...sourceFiles.map((_, index) => `fn${index}`),
    ...childCategories.map((_, index) => `...category${index}`),
  ];
  const body = [generatedHeader, ...imports, "", ...renderArray(exports), ""].join("\n");
  generatedFiles.set(join(directory, "index.ts"), body);
  return true;
}

const rootCategories = readdirSync(functionsRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .sort((a, b) => a.name.localeCompare(b.name))
  .filter((entry) => generateDirectory(join(functionsRoot, entry.name)))
  .map((entry) => entry.name);

const rootImports = rootCategories.map(
  (category, index) => `import category${index} from "./${category}";`,
);
const rootExports = rootCategories.map((_, index) => `...category${index}`);
generatedFiles.set(
  join(functionsRoot, "list.ts"),
  [generatedHeader, ...rootImports, "", ...renderArray(rootExports), ""].join("\n"),
);

for (const [file, contents] of generatedFiles) {
  if (contents === null) unlinkSync(file);
  else writeFileSync(file, contents);
}

console.log(`Generated ${generatedFiles.size} function indexes.`);
